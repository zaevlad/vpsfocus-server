#!/bin/sh
# Уборка каталога прогона, когда итог установки уже у приложения.
# МЕНЯЕТ: удаляет /opt/vpsfocus.run. Модуль: stack.rs (discard_run_script).
#
# До прочтения итога каталог — улика, после — след на чужом сервере, которого
# мы не обещали оставлять. Только свой прогон, по идентификатору: между
# «итог прочитан» и этой уборкой другая копия приложения могла завести новую
# установку, и слепое `rm -rf` снесло бы журнал её живого прогона.
#
# Параметры:
#   RUN — каталог прогона, /opt/vpsfocus.run;
#   ID  — идентификатор своего прогона.

SUDO=""
[ "$(id -u)" = 0 ] || SUDO="sudo -n"
if [ "$($SUDO cat "$RUN/id" 2>/dev/null || true)" = "$ID" ]; then $SUDO rm -rf "$RUN"; fi
