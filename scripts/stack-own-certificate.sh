#!/bin/sh
# Свой сертификат мониторинга, если человек его вводил: срок и имена — для
# напоминания о продлении. ТОЛЬКО ЧТЕНИЕ. Модуль: stack.rs (own_certificate).
#
# Читается только сертификат — он публичен, его отдают каждому посетителю.
# Ключ остаётся на сервере.
#
# Параметры:
#   DIR      — каталог стека, /opt/vpsfocus;
#   TLS_MODE — значение TLS_MODE в .env, при котором сертификат свой (file);
#   CERT     — путь к сертификату внутри каталога стека, tls/cert.pem.

SUDO=""
[ "$(id -u)" = 0 ] || SUDO="sudo -n"
$SUDO grep -q "^TLS_MODE=$TLS_MODE\$" "$DIR/.env" 2>/dev/null || exit 0
$SUDO cat "$DIR/$CERT" 2>/dev/null || true
