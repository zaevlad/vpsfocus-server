#!/bin/sh
# Чтение пары «сертификат — ключ», которую человек выбрал из найденных.
# ТОЛЬКО ЧТЕНИЕ. Модуль: certscan.rs (read_pair).
#
# Ключ приезжает в приложение и тут же уезжает обратно — в каталог стека на
# том же сервере (put.sh), дальше той же дорогой, что вставленный руками. На
# сервер vpsFocus он не уходит; в текст ошибки попадает путь, а не
# содержимое.
#
# Параметры:
#   CERT — путь к сертификату;
#   KEY  — путь к ключу.
# Приложение пропускает только абсолютные пути без кавычек и подстановок.

SUDO=""
[ "$(id -u)" = 0 ] || SUDO="sudo -n"
printf '::cert\n'
$SUDO cat "$CERT" 2>/dev/null || true
printf '\n::key\n'
$SUDO cat "$KEY" 2>/dev/null || true
printf '\n::end\n'
