#!/bin/sh
# Чтение файла настроек мониторинга вместе с его хешем: agent.env, списки
# сайтов, страниц, логов, проектов, ключевых адресов. ТОЛЬКО ЧТЕНИЕ.
# Модуль: agent.rs (read_remote_checked).
#
# Хеш считает сервер, а не приложение: по нему запись поверх свежего
# (write-file.sh) узнаёт, не изменил ли файл кто-то из команды между
# чтением и записью. Нет файла — пустой хеш.
#
# Параметры:
#   FILE — путь к файлу в каталоге стека.

SUDO=""
[ "$(id -u)" = 0 ] || SUDO="sudo -n"
echo '::hash'
$SUDO sha256sum "$FILE" 2>/dev/null | cut -d' ' -f1 || true
echo '::content'
$SUDO cat "$FILE" 2>/dev/null || true
