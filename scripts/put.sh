# Заливка файла в каталог стека: функция `put`, общая для установки,
# обновления и замены сертификата. Сама ничего не делает — её вызывают
# строки, которые приложение ставит на место метки @UPLOADS@:
#
#   put '/opt/vpsfocus/.env' 600 <<'VPSFOCUS_FILE_EOF_9f13c2'
#   …содержимое файла…
#   VPSFOCUS_FILE_EOF_9f13c2
#
# Содержимое приходит на stdin через heredoc, а не аргументом: аргументы
# видны в списке процессов сервера, а в .env лежат пароли. Строку, совпавшую
# с разделителем, приложение не пропустит — она оборвала бы файл молча.
#
# Права ставятся до появления файла под рабочим именем (umask 077 и chmod на
# временном файле), а `mv` делает подмену целиком: оборванная заливка не
# оставит полфайла на месте рабочего.

put() {
    put_path="$1"
    put_mode="$2"
    $SUDO mkdir -p "$(dirname "$put_path")"
    $SUDO sh -c 'umask 077; cat > "$1.new"' put "$put_path"
    $SUDO chmod "$put_mode" "$put_path.new"
    $SUDO mv "$put_path.new" "$put_path"
}
