#!/bin/sh
# Тело запуска установки: выполняется под root внутри stack-launch.sh.
#
# Параметры:
#   ROOT       — каталог стека, /opt/vpsfocus;
#   DIR        — куда заливать файлы: сам каталог стека (установка) или его
#                подкаталог .staged (обновление: снимок для отката снимается
#                уже на сервере, и подменять работающие файлы заранее нельзя);
#   RUN        — каталог прогона, /opt/vpsfocus.run: рядом с каталогом стека,
#                а не внутри — откат первой установки удаляет каталог целиком;
#   RUN_SCRIPT — что запускать: install.sh или update.sh;
#   ID         — идентификатор прогона: по нему приложение отличает свой
#                прогон от прогона другой копии приложения;
#   META       — описание прогона строками `ключ=значение` (id, kind,
#                version, domain, port) для приложения, вернувшегося к
#                незаконченной установке.
# На месте @UPLOADS@ — функция `put` (put.sh) и заливка файлов бандла.
#
# Коды выхода до запуска установки: 127 — на сервере нет flock, 75 — замок
# занят другой установкой, 70 и 71 — не открылся /opt или не завёлся каталог
# прогона.

set -eu
SUDO=""
[ "$(id -u)" = 0 ] || SUDO="sudo -n"

# Без flock замок не взять, и работать «как-нибудь» тут нельзя: две
# установки разом ломают стек.
command -v flock >/dev/null 2>&1 || exit 127

# Замок Р8 — на /opt, родителе каталога стека, и на открытом дескрипторе:
# такой замок держится, пока открыт дескриптор, а дескриптор наследует
# отвязанный потомок. Замок снимается вместе с концом установки.
exec 9</opt || exit 70
flock -n 9 || exit 75

# Каталог прогона заводим заново под замком: пока он у нас, чужого живого
# прогона на сервере нет, и затирать нечего.
rm -rf "$RUN"
mkdir -m 700 "$RUN" || exit 71

# Заливка тоже умеет провалиться: диск полон, файловая система только для
# чтения. Без этой ловушки такой сбой остался бы без маркера.
UPLOADED=0
trap '[ "$UPLOADED" = 1 ] || printf "::step:preflight\n::fail:preflight:uploadFailed\n"' EXIT

$SUDO mkdir -p "$DIR"

@UPLOADS@

# Заливка позади: дальше отвечает уже install.sh со своими маркерами.
UPLOADED=1
trap - EXIT

# Описание прогона — до его запуска: приложение, вернувшееся к
# незаконченной установке, читает именно его.
printf '%s' "$META" > "$RUN/meta"
printf '%s\n' "$ID" > "$RUN/id"
chmod 600 "$RUN/meta" "$RUN/id"

# Отвязываем установку от сессии SSH: обрыв связи больше её не убивает.
#
# stdin закрыт: без перенаправления install.sh съел бы остаток этого же
# скрипта. stderr сливается в stdout — маркеры шагов и текст ошибок должны
# попасть в журнал в исходном порядке. Нет setsid — хватает nohup: без
# псевдотерминала sshd не шлёт процессу SIGHUP.
#
# Без $SUDO намеренно: внутри замка мы уже root, а `sudo` закрывает чужие
# дескрипторы (`closefrom`) — замок на дескрипторе 9 до потомка не доехал
# бы, и вторая копия приложения начала бы установку поверх.
#
# Путь к скрипту уходит аргументом, а не переменной окружения: окружение
# install.sh остаётся тем же, что было до выноса скриптов в файлы, — в нём
# только RUN.
export RUN
if command -v setsid >/dev/null 2>&1; then DETACH=setsid; else DETACH=nohup; fi
$DETACH sh -c '
printf "%s\n" "$$" > "$RUN/pid"
sh "$1" </dev/null >>"$RUN/log" 2>&1
printf "%s\n" "$?" > "$RUN/done"
' launch "$ROOT/$RUN_SCRIPT" </dev/null >/dev/null 2>&1 &

# Отметка «завели» — в stderr: stdout разбирается теми же маркерами, что и
# журнал прогона, и лишняя строка в нём стала бы строкой на экране.
printf '::launched\n' >&2
exit 0
