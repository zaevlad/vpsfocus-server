#!/bin/sh
# Замок на операцию над стеком (Р8): восстановление копии, снос стека,
# уборка прерванной установки. Модули: stack.rs (lock_on_opt), lifecycle.rs.
#
# Обёртка: тело операции (restore.sh, wipe.sh, stack-cleanup.sh) встаёт на
# место @BODY@ и выполняется под `flock` на /opt. Две такие операции разом
# на чужом сервере — сломанный стек.
#
# Замок — на /opt, родителе каталога стека, а не на нём самом: откат первой
# установки удаляет каталог целиком, и замок остался бы висеть на снятой
# иноде. Тело — во вложенном `sh -s` через heredoc: в нём много одиночных
# кавычек, и обернуть его в `sh -c '…'` значило бы гонку экранирований.
# `exec` — операция становится этим же процессом, и замок снимается только
# вместе с её завершением.
#
# Коды: 75 — замок занят другой копией приложения (без ожидания), 127 — на
# сервере нет flock.

set -eu
SUDO=""
[ "$(id -u)" = 0 ] || SUDO="sudo -n"
exec $SUDO flock -n -E 75 /opt sh -s <<'VPSFOCUS_LOCK_EOF_2f9c7a'
@BODY@
VPSFOCUS_LOCK_EOF_2f9c7a
