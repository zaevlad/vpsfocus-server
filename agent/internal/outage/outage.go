// Package outage собирает то, что было на сервере вокруг заданного часа.
//
// Задача одна: рядом с «сайт лежал» показать «вот что при этом
// происходило». Инцидент фиксирует наша инфраструктура снаружи, а всё
// остальное — замеры, ошибки из логов, отметки журнала — лежит здесь, у
// агента.
//
// **Во время падения данных нет, и это надо показать, а не чинить.** Лежал
// сервер — лежал и агент, и в окне аварии у него пусто. Пустота при этом не
// «ничего не происходило», а диагноз: сервер не отвечал. Поэтому провалы в
// замерах считаются отдельно и уезжают наружу списком, а рядом с окном
// всегда идёт последний замер **перед** ним — то единственное, что об
// аварии вообще известно.
//
// **Часы не сходятся, и на этом функция ломается молча.** Инцидент записан
// по нашим часам, замеры — по часам сервера клиента, и расходятся они на
// минуты. Окно «покажи, что было в 3:12» промахнулось бы мимо данных без
// всякой ошибки. Поэтому приложение присылает своё время, агент считает
// расхождение сам и сдвигает окно на него — и говорит, на сколько сдвинул.
package outage

import (
	"time"

	"agent/internal/events"
	"agent/internal/logs"
	"agent/internal/metrics"
)

// Во сколько раз промежуток между замерами должен превысить обычный, чтобы
// считаться провалом.
//
// Три, а не два: замер снимается тикером, и один пропущенный тик — это
// затянувшийся сбор метрик, а не упавший сервер. Объявлять аварией каждую
// подвисшую секунду значит утопить настоящие провалы в шуме.
const gapFactor = 3

// Gap — промежуток, за который агент не записал ни одного замера.
type Gap struct {
	From time.Time `json:"from"`
	To   time.Time `json:"to"`
	// Длина в минутах, уже посчитанная: экран показывает её на трёх
	// языках чисел, а не пересчитывает разницу дат.
	Minutes int `json:"minutes"`
}

// Window — что было вокруг указанного времени.
type Window struct {
	// Время агента в UTC. По нему приложение сверяет часы, и по нему же
	// читаются все остальные времена в этом ответе.
	AgentTime time.Time `json:"agentTime"`
	// На сколько секунд часы сервера впереди наших. Отрицательное — отстают.
	SkewSeconds int `json:"skewSeconds"`
	// Окно, которое агент действительно посмотрел, — уже сдвинутое на
	// расхождение часов.
	From time.Time `json:"from"`
	To   time.Time `json:"to"`

	// Последний замер перед окном. Пусто — замеров не было вовсе.
	Before *metrics.Sample `json:"before,omitempty"`
	// Замеры внутри окна.
	Samples []metrics.Sample `json:"samples"`
	// Провалы: агент не писал, значит его не было.
	Gaps []Gap `json:"gaps"`

	// Ошибки веб-сервера за окно: разрез по группам и ряд для графика.
	LogGroups []logs.Group `json:"logGroups"`
	LogSeries []logs.Point `json:"logSeries"`

	// Отметки журнала за окно, от новых к старым.
	Events []events.Event `json:"events"`
}

// Skew — насколько часы агента впереди часов приложения.
//
// Пустое время приложения означает «не спрашивали»: сдвигать нечего, и
// притворяться, что часы сошлись, тоже нельзя — наружу уходит ноль, и это
// честно ровно настолько, насколько честен вопрос без второй половины.
func Skew(agentNow, appNow time.Time) time.Duration {
	if appNow.IsZero() {
		return 0
	}
	return agentNow.Sub(appNow).Round(time.Second)
}

// Gaps находит промежутки без замеров.
//
// Границы окна участвуют наравне с самими замерами: авария, начавшаяся до
// окна и кончившаяся внутри, даёт провал от `from` до первого замера, и не
// показать его значило бы начать рассказ с середины. Верхнюю границу
// вызывающий обязан обрезать по «сейчас» — будущее не провал, а будущее.
func Gaps(samples []metrics.Sample, from, to time.Time, interval time.Duration) []Gap {
	if !to.After(from) {
		return []Gap{}
	}
	if interval <= 0 {
		interval = time.Minute
	}
	longest := interval * gapFactor

	// Замеров нет вовсе — провал во всё окно. Это самый частый случай
	// разбора аварии, а не крайний: агент лежал вместе с сервером.
	if len(samples) == 0 {
		return []Gap{gap(from, to)}
	}

	found := []Gap{}
	previous := from
	for _, sample := range samples {
		if sample.At.Sub(previous) > longest {
			found = append(found, gap(previous, sample.At))
		}
		previous = sample.At
	}
	if to.Sub(previous) > longest {
		found = append(found, gap(previous, to))
	}
	return found
}

func gap(from, to time.Time) Gap {
	minutes := int(to.Sub(from).Minutes())
	// Провал короче минуты всё равно провал: округлив его в ноль, мы
	// написали бы «сервер не отвечал 0 минут».
	if minutes < 1 {
		minutes = 1
	}
	return Gap{From: from.UTC(), To: to.UTC(), Minutes: minutes}
}
