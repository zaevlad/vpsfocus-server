// Package text — обрезка строк по символам, а не по байтам.
//
// Отдельный пакет ради одной функции заведён потому, что резать строки
// приходится в трёх местах трёх разных пакетов (заголовок страницы при
// обходе, пример сообщения из лога, текст отказа Google), а срезать байты
// вместо символов — ошибка, которую нельзя допустить ни в одном из них:
// оборванная посередине руна превращает сообщение в мусор, который потом
// ищут глазами в интерфейсе, а в SQLite агента ложится строкой, которую уже
// не прочитать. Три копии этой правки однажды разошлись бы, и разошлась бы
// именно та, которую забыли.
//
// Тот же пакет с тем же именем есть у backend. Общим он быть не может:
// агент и backend — разные модули, и `go.work` в репозитории нет намеренно,
// потому что агент уезжает на чужой сервер отдельной сборкой. Две копии
// одной функции здесь дешевле связи двух модулей.
package text

import "unicode/utf8"

// Truncate оставляет от строки не больше limit символов.
//
// Считаем символы, а не байты: предел в байтах обещал бы одну длину, а
// кириллице отмерял вдвое меньшую — и на границе резал бы руну пополам.
func Truncate(s string, limit int) string {
	if limit <= 0 {
		return ""
	}
	if utf8.RuneCountInString(s) <= limit {
		return s
	}

	count := 0
	for offset := range s {
		if count == limit {
			return s[:offset]
		}
		count++
	}
	return s
}
