// Package seo обходит сайт клиента и снимает с каждой страницы структуру,
// по которой потом судят о его поисковой пригодности.
//
// Краулер здесь свой и отдельный от того, что живёт в internal/links. Тот
// собирает список страниц, чтобы отдать его lychee, и больше ничего о них не
// помнит; SEO-аудиту нужно сохранённое содержимое — заголовки, описания,
// canonical, alt-тексты. Свести оба обхода в один заманчиво, но это значит
// переписать работающую с тринадцатого спринта проверку ссылок ради экономии
// одного прохода по сайту.
//
// Хранится не HTML, а извлечённая структура. Страница сайта — это сотня
// килобайт разметки, из которых для аудита нужен килобайт; держать остальное
// на диске, который нам не принадлежит, незачем.
//
// robots.txt соблюдается строго и без выключателя. Сайт принадлежит
// агентству, но агент всё равно бот на живом сервере: закрытые от поисковика
// разделы — админка, корзина, фильтры — в SEO-отчёте и не нужны, их всё
// равно не индексирует Google.
package seo

import (
	"regexp"
	"time"
)

// Как агент представляется сайту. Имя постоянное: по нему владелец сайта
// узнаёт нас в своих логах и по нему же адресует нам правила robots.txt.
const UserAgent = "vpsfocus-seo"

// Коды ошибок обхода. Перевод — в приложении, как и везде: интерфейс
// двуязычный, и собирать текст в агенте значило бы держать переводы в двух
// местах.
const (
	// robots.txt не отдался вовсе — сеть или 5xx. По RFC 9309 это значит
	// «не ходить»: сервер не сказал, что можно, и решать за него мы не
	// станем. Обход не проводится, и экран говорит об этом прямо.
	ErrRobotsUnavailable = "seoRobotsUnavailable"
	// robots.txt закрыл сайт целиком. Пустой результат — это отказ, а не
	// «всё хорошо»: без отдельного кода экран показал бы «0 из 0 страниц»
	// и число закрытых адресов, ни словом не объяснив причину. Тот же
	// выбор и по той же причине, что у проверки ссылок.
	ErrRobotsForbidden = "seoRobotsForbidden"
	// Стартовая страница недоступна: сайта нет, домен не резолвится,
	// сертификат просрочен.
	ErrStartUnreachable = "seoStartUnreachable"
	// Обход не уложился в отведённое время.
	ErrTimeout = "seoScanTimeout"
	// Обход не принёс ни одной страницы, и причина не в robots.txt и не во
	// времени. Так выглядит правило исключений (`SEO_EXCLUDE`), накрывшее
	// главную: стартовый адрес отбрасывался молча, обход заканчивался с
	// нулём страниц и пустым `run_error`, и экран продолжал показывать
	// вчерашний снимок, ни словом не сказав, что сегодняшний не состоялся.
	// Молчаливый ноль хуже отказа — даже когда виновата наша же настройка,
	// а не чужой сервер.
	ErrNoPages = "seoNoPages"
	// Всё остальное.
	ErrScanFailed = "seoScanFailed"
)

// Коды ошибок отдельной страницы. Страница с ошибкой всё равно сохраняется:
// «недоступна» — это результат аудита, а не его отсутствие.
const (
	PageErrNetwork      = "seoPageNetwork"
	PageErrTimeout      = "seoPageTimeout"
	PageErrStatus       = "seoPageStatus"
	PageErrTooLarge     = "seoPageTooLarge"
	PageErrRedirectLoop = "seoPageRedirectLoop"
	PageErrOffsite      = "seoPageRedirectOffsite"
	PageErrNotHTML      = "seoPageNotHTML"
)

// Scan — итог одного обхода одного сайта.
//
// Страницы лежат отдельно: их сотни, и экрану сводки они не нужны.
type Scan struct {
	Domain string `json:"domain"`
	// Когда начался обход.
	CheckedAt string `json:"checkedAt"`
	// Сколько занял весь обход.
	DurationSeconds int64 `json:"durationSeconds"`
	Stats           Stats `json:"stats"`
	// Почему обход не состоялся. Пусто — всё получилось.
	//
	// Заполнено вместе с пустой сводкой это значит, что состоявшихся
	// обходов у сайта ещё не было вовсе: показывать нечего, и причина —
	// единственное, что мы можем сказать.
	Error string `json:"error,omitempty"`
	// Когда была последняя попытка обхода и чем она кончилась, если после
	// показанного обхода были неудачные.
	//
	// Отдельно от `Error`, а не вместо показанного обхода: один
	// перенаправленный robots.txt не повод стереть с экрана снимок сайта
	// на пятьсот страниц, а промолчать о неудавшейся попытке — значит
	// выдать вчерашние данные за сегодняшние.
	FailedAt    string `json:"failedAt,omitempty"`
	FailedError string `json:"failedError,omitempty"`
	// Сводки прошлых обходов, от старых к новым, кроме последнего: он и
	// так показан целиком.
	History []HistoryPoint `json:"history,omitempty"`
	// Что изменилось в перечне проверок с прошлого обхода. Пусто — сравнить
	// не с чем: обход первый или у прошлых нет перечня.
	Progress *Progress `json:"progress,omitempty"`
}

// Stats — что получилось за обход.
//
// Не «сколько страниц», а из чего эти страницы состоят: сайт, у которого
// половина адресов отвечает перенаправлением, и сайт, у которого половина
// закрыта от индексации, — это две разные беды, и различать их надо до
// всякого разбора.
type Stats struct {
	// Сколько страниц сохранено — с ошибками и без.
	Pages int `json:"pages"`
	// Сколько из них удалось скачать и разобрать.
	Fetched int `json:"fetched"`
	// Сколько ответили ошибкой или не ответили вовсе.
	Failed int `json:"failed"`
	// Сколько пришли через перенаправление.
	Redirected int `json:"redirected"`
	// Сколько оказались копией уже виденной страницы по содержимому.
	Duplicates int `json:"duplicates"`
	// Сколько закрыты от индексации сами (meta robots или заголовок).
	Noindex int `json:"noindex"`
	// Сколько адресов не тронуты из-за robots.txt.
	BlockedByRobots int `json:"blockedByRobots"`
	// Сколько адресов пришло из карты сайта.
	FromSitemap int `json:"fromSitemap"`
	// Сколько адресов осталось в очереди, когда обход упёрся в потолок.
	// Ноль означает, что сайт обойдён целиком, — и это единственный
	// честный способ сказать «показано не всё».
	Queued int `json:"queued"`
	// Пауза между запросами, с которой шёл обход. Crawl-delay из
	// robots.txt может оказаться больше нашей настройки, и тогда обход
	// идёт медленнее, чем просили, — экран обязан это объяснить.
	DelayMS int64 `json:"delayMs"`
	// Что нашёл разбор структуры. Живёт здесь, а не отдельной колонкой,
	// потому что сводка обхода и сводка находок отвечают на один вопрос —
	// «что у сайта сейчас», — и в истории они нужны вместе.
	Issues IssueSummary `json:"issues"`
	// Как открывается сам сайт: http, www и вариант без www. Пусто —
	// проверка не проводилась: обход не состоялся, и спрашивать про входы
	// на сайт, которого мы не видели, нечего.
	//
	// Здесь же, а не рядом со Scan, по той причине, по которой здесь лежат
	// находки: сводка едет в базу одним полем, а заводить колонку ради
	// трёх строк значило бы завести агенту миграции.
	Canonical *CanonicalReport `json:"canonical,omitempty"`
	// Сайт целиком: robots.txt, кому открыт сайт, карта сайта. Пусто у
	// обходов агента старше 0.16.0 и у обхода, не прочитавшего robots.txt.
	Site *SiteReport `json:"site,omitempty"`
	// Перечень проверок с исходом каждой (трек U, `checks.go`). Пусто у
	// обходов, сохранённых агентом до 0.18.0, — им он достраивается при
	// чтении (`EnsureChecks`), — и у обхода, не принёсшего страниц.
	Checks *ChecksReport `json:"checks,omitempty"`
}

// HistoryPoint — сводка прошлого обхода без страниц.
//
// Числа находок здесь ради динамики: «было двести страниц без описания,
// стало десять» — это единственное, что показывает работу, и без истории
// такой ответ взять неоткуда.
type HistoryPoint struct {
	CheckedAt string `json:"checkedAt"`
	Pages     int    `json:"pages"`
	Fetched   int    `json:"fetched"`
	Failed    int    `json:"failed"`
	Critical  int    `json:"critical"`
	Warning   int    `json:"warning"`
	Notice    int    `json:"notice"`
	// Счёт перечня проверок: «было пройдено 42 из 56». Пусто у неудачной
	// попытки и у обхода агента старше 0.16.0 — перечня у них нет.
	Checks *CheckTally `json:"checks,omitempty"`
}

// Page — одна страница сайта: как она отвечала и что на ней нашли.
type Page struct {
	// Адрес, по которому пришли, — нормализованный.
	URL string `json:"url"`
	// Куда привели перенаправления. Пусто — никуда не вели.
	FinalURL string `json:"finalUrl,omitempty"`
	// Цепочка перенаправлений, от первого к последнему.
	Redirects []string `json:"redirects,omitempty"`
	Status    int      `json:"status"`
	// Сколько переходов от главной страницы. Адреса из карты сайта — ноль:
	// владелец сайта назвал их сам, и по ссылкам они могут быть не видны.
	Depth       int    `json:"depth"`
	ContentType string `json:"contentType,omitempty"`
	Bytes       int    `json:"bytes"`
	LoadMS      int64  `json:"loadMs"`
	// Отпечаток содержимого: по нему видно копии страниц внутри одного
	// обхода. Сравнения с прошлым обходом по нему нет — и обещать его
	// незачем: разницу между обходами показывает сравнение находок
	// (`diff.go`), а «байт в байт то же самое» у живой страницы не значит
	// ничего — там меняются счётчики, даты и рекламные блоки.
	Hash string `json:"hash,omitempty"`
	// Адрес страницы, копией которой эта оказалась.
	DuplicateOf string `json:"duplicateOf,omitempty"`
	// Пришла ли из карты сайта.
	FromSitemap bool `json:"fromSitemap,omitempty"`
	// Есть ли адрес в карте сайта. Не то же самое, что `FromSitemap`: в
	// очередь из карты идёт не больше половины потолка страниц, и страница
	// из карты сверх него найдётся по ссылке — оставаясь в карте.
	InSitemap bool `json:"inSitemap,omitempty"`
	// Код ошибки страницы. Пусто — страница скачана.
	Error string `json:"error,omitempty"`
	// Структура. Её нет у страницы с ошибкой и у не-HTML.
	Structure *Structure `json:"structure,omitempty"`
	// Находки аудита по этой странице. Считаются при обходе, вместе со
	// структурой: пороги живут в агенте, а наружу уходят коды.
	Issues []Issue `json:"issues,omitempty"`
}

// Structure — то, ради чего затевался обход.
//
// Разбор здесь, а не при чтении из базы: страницу мы держим в памяти ровно
// один раз, и второй возможности снять с неё структуру не будет — HTML мы
// не храним.
type Structure struct {
	Title           string `json:"title,omitempty"`
	MetaDescription string `json:"metaDescription,omitempty"`
	// Содержимое meta name=robots как есть.
	MetaRobots string `json:"metaRobots,omitempty"`
	// Заголовок X-Robots-Tag: то же указание, но со стороны сервера. Его
	// легко не заметить, потому что в разметке его нет вовсе.
	XRobotsTag string `json:"xRobotsTag,omitempty"`
	Canonical  string `json:"canonical,omitempty"`
	// Указывает ли canonical на саму страницу. Ложь означает либо
	// осознанную склейку, либо копипасту шаблона — а это уже вопрос
	// разбора, не обхода.
	CanonicalSelf bool     `json:"canonicalSelf,omitempty"`
	Lang          string   `json:"lang,omitempty"`
	HasViewport   bool     `json:"hasViewport,omitempty"`
	Noindex       bool     `json:"noindex,omitempty"`
	Nofollow      bool     `json:"nofollow,omitempty"`
	H1            []string `json:"h1,omitempty"`
	H2            []string `json:"h2,omitempty"`
	H3            []string `json:"h3,omitempty"`
	// Open Graph по именам без префикса: title, description, image, type, url.
	OpenGraph map[string]string `json:"openGraph,omitempty"`
	Images    Images            `json:"images"`
	Links     LinkCounts        `json:"links"`
	// Слов в видимом тексте. Тонкая страница — обычная находка аудита, и
	// пересчитать её слова потом будет нечем: текст мы тоже не храним.
	WordCount int `json:"wordCount"`
}

// Images — картинки страницы. Хранятся счётчики и несколько примеров:
// список всех картинок сайта — это те же гигабайты, только в профиль.
type Images struct {
	Total      int      `json:"total"`
	WithoutAlt int      `json:"withoutAlt"`
	Samples    []string `json:"samples,omitempty"`
}

// LinkCounts — ссылки страницы.
type LinkCounts struct {
	Internal int `json:"internal"`
	External int `json:"external"`
	Nofollow int `json:"nofollow"`
}

// Limits — пределы обхода.
//
// Всё консервативно по умолчанию: это чужой прод, и обход не имеет права
// мешать работе сайта, ради которого его затеяли.
type Limits struct {
	// Сколько переходов от главной разрешено.
	MaxDepth int
	// Потолок числа страниц на сайт за один обход.
	MaxPages int
	// Сколько байт читать со страницы. Остальное отбрасывается: разметку
	// в мегабайт разбирать незачем, а память агента не наша.
	MaxBytes int64
	// Пауза между запросами к сайту. Crawl-delay из robots.txt, если он
	// больше, заменяет её собой.
	Delay time.Duration
	// Таймаут одного запроса.
	Timeout time.Duration
	// Куда не ходить помимо robots.txt: регулярки по адресу целиком.
	Exclude []*regexp.Regexp
	// Читать ли карту сайта. В ней лежат страницы, на которые не ведёт ни
	// одна ссылка, — а это ровно то, что аудит обязан заметить.
	UseSitemap bool
}
