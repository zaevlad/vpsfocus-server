// Package events — журнал того, что происходило на сервере.
//
// Половина вопроса «почему сайт лежал» — это «что при этом менялось».
// Замеры и счётчики отвечают на «как было плохо», но не на «что мы сделали
// за минуту до»: обновили стек, перезагрузили сервер, агент перезапустился.
// Без этих отметок разбор аварии превращается в гадание по графику.
//
// **Журнала два, и свести их может только приложение.** События установки и
// обновления рождаются на машине пользователя (`journal.rs`), события
// сервера — здесь. Тащить одно в другое нечем: приложение в момент
// перезапуска агента закрыто, а агент об установке узнаёт только тем, что
// его запустили. Сводит их экран.
//
// **Наружу уходят коды, а не текст** — как и у свода состояния, и по той же
// причине: интерфейс двуязычный, а агент обновляется отдельно от него.
// Полнота переводов закреплена тестом приложения, который читает список
// прямо отсюда.
package events

import "time"

// Event — одна отметка в журнале сервера.
type Event struct {
	// Время по часам сервера, в UTC. Часы сервера уезжают на минуты — это
	// обычное дело, — поэтому наружу вместе с событиями уходит и
	// расхождение: сводить два журнала на одну ленту иначе нельзя.
	At time.Time `json:"at"`
	// Код события. Текст собирает приложение.
	Kind string `json:"kind"`
	// О чём речь: домен, файл, вид проверки. Пусто — событие про сервер
	// целиком.
	Target string `json:"target,omitempty"`
	// Уточнение — тоже код, а не текст, и читается по коду события: у
	// тревог здесь вид проверки (`checks.Kind*`), у кругов — признак того,
	// что круг не дошёл до конца.
	Detail string `json:"detail,omitempty"`
}

// Круг оборвали: кончилось отведённое ему время или остановили агента.
//
// Один код на все три круга, а не разбор причины: подробности того, что
// именно не заладилось на каком сайте, лежат в отчёте самого круга и на его
// экране. Лента отвечает на вопрос «что происходило», а не «почему не
// получилось».
const DetailInterrupted = "eventRoundInterrupted"

// Коды событий агента.
//
// Список короткий намеренно. Лента, в которую пишут каждый проход по логам,
// нечитаема через сутки, а нужна она ровно тогда, когда что-то случилось:
// в ней должны быть перемены, а не пульс.
const (
	// Агент запустился. Он же — след обновления стека и падения сервера:
	// сам по себе агент не перезапускается.
	KindAgentStarted = "eventAgentStarted"
	// Сервер перезагрузился: время его работы стало меньше, чем было в
	// прошлом замере.
	KindServerRebooted = "eventServerRebooted"

	// Агент позвал человека: беда и её конец.
	//
	// Записывается тогда же, когда уходит письмо, а не когда беда
	// обнаружена. Второе состояние тревоги (одно для писем, другое для
	// журнала) разошлось бы с первым, и разошлось бы то, про которое
	// забыли. Цена решения: беда, случившаяся при ненастроенных каналах, в
	// ленте не появится — но о немых каналах свод говорит отдельным
	// поводом `healthNoChannels`.
	KindAlertFiring   = "eventAlertFiring"
	KindAlertResolved = "eventAlertResolved"

	// Круги, которые ходят на сайт клиента. Пустой `Detail` — круг
	// состоялся, иначе в нём код беды.
	KindLinksScan  = "eventLinksScan"
	KindVitalsScan = "eventVitalsScan"
	KindSeoScan    = "eventSeoScan"

	// Окно обслуживания: человек сам сказал, что чинит.
	KindMaintenanceStarted = "eventMaintenanceStarted"
	KindMaintenanceEnded   = "eventMaintenanceEnded"

	// Ключевой адрес проекта перестал работать и снова заработал.
	//
	// Записывается на переломе, а не каждый круг: круг ходит каждые
	// несколько минут, и «адрес не отвечает» триста раз в сутки — это не
	// лента, а шум.
	KindProbeFailing   = "eventProbeFailing"
	KindProbeRecovered = "eventProbeRecovered"

	// Клиент сказал, что задеплоил: дёрнули хук.
	//
	// В ленте это самая ценная строка из всех: рядом с ней видно, что
	// сломалось сразу после выкатки.
	KindDeployed = "eventDeployed"

	// Еженедельный отчёт ушёл.
	KindDigestSent = "eventDigestSent"

	// Копия базы: сделана и не сделалась.
	//
	// Раз в сутки, то есть две строки в неделю на самой болтливой
	// настройке, — это перемена, а не пульс: копия либо появилась, либо
	// нет, и в разборе «почему после переезда потерялся день» это первое,
	// что смотрят. В `Detail` неудачи лежит код беды.
	KindBackupDone   = "eventBackupDone"
	KindBackupFailed = "eventBackupFailed"
)
